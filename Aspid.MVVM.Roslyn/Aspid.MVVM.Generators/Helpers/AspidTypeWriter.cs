#nullable enable

using System.Collections.Generic;
using Aspid.Generators.Helper;
using Aspid.MVVM.Generators.Shared;

namespace Aspid.MVVM.Generators.Helpers;

internal static class AspidTypeWriter
{
    internal static CodeWriter BeginScopedClass(
        this CodeWriter code,
        AspidTypeDeclaration declaration,
        IEnumerable<string>? bases = null) =>
        code.BeginScopedClass(System.Array.Empty<string>(), declaration, bases);

    internal static CodeWriter BeginScopedClass(
        this CodeWriter code,
        IEnumerable<string> usings,
        AspidTypeDeclaration declaration,
        IEnumerable<string>? bases)
    {
        code.AppendLine("// <auto-generated>");
        foreach (var directive in usings)
            code.AppendLine("using " + directive + ";");
        if (!string.IsNullOrEmpty(declaration.Namespace))
            code.AppendLine("namespace " + declaration.Namespace).BeginBlock();
        foreach (var container in declaration.Containers)
            code.AppendLine(AspidTypeDeclaration.Header(container)).BeginBlock();
        return code.AppendLine(AspidTypeDeclaration.Header(declaration.Symbol, bases)).BeginBlock();
    }

    internal static CodeWriter EndScopedClass(this CodeWriter code, AspidTypeDeclaration declaration)
    {
        code.EndBlock();
        foreach (var container in declaration.Containers)
            code.EndBlock();
        if (!string.IsNullOrEmpty(declaration.Namespace))
            code.EndBlock();
        return code;
    }
}
